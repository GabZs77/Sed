const helper = await import('./push-worker.mjs');
assert.equal(typeof helper.encryptPushPayload, 'function');
const clientKeys = await crypto.subtle.generateKey({ name: 'ECDH', namedCurve: 'P-256' }, true, ['deriveBits']);
const clientPublic = new Uint8Array(await crypto.subtle.exportKey('raw', clientKeys.publicKey));
const auth = crypto.getRandomValues(new Uint8Array(16));
const toBase64Url = (bytes) => Buffer.from(bytes).toString('base64url');
const encryptedRecord = await helper.encryptPushPayload({ keys: { p256dh: toBase64Url(clientPublic), auth: toBase64Url(auth) } }, { title: 'Teste' });
assert.ok(encryptedRecord.length > 100, 'O payload deve ser convertido em registro aes128gcm.');
assert.equal(encryptedRecord[20], 65, 'O registro deve incluir a chave pública efêmera P-256.');
const serverPublic = await crypto.subtle.importKey('raw', encryptedRecord.slice(21, 86), { name: 'ECDH', namedCurve: 'P-256' }, false, []);
const shared = new Uint8Array(await crypto.subtle.deriveBits({ name: 'ECDH', public: serverPublic }, clientKeys.privateKey, 256));
const hmac = async (keyBytes, data) => {
  const key = await crypto.subtle.importKey('raw', keyBytes, { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  return new Uint8Array(await crypto.subtle.sign('HMAC', key, data));
};
const authPrk = await hmac(auth, shared);
const expand = async (prk, info, size) => hmac(prk, new Uint8Array([...info, 1])).then((bytes) => bytes.slice(0, size));
const fromBase64Url = (value) => new Uint8Array(Buffer.from(value, 'base64url'));
const vectorShared = fromBase64Url('kyrL1jIIOHEzg3sM2ZWRHDRB62YACZhhSlknJ672kSs');
const vectorAuth = fromBase64Url('BTBZMqHH6r4Tts7J_aSIgg');
const vectorUaPublic = fromBase64Url('BCVxsr7N_eNgVRqvHtD0zTZsEc6-VV-JvLexhqUzORcxaOzi6-AYWXvTBHm4bjyPjs7Vd8pZGH6SRpkNtoIAiw4');
const vectorAsPublic = fromBase64Url('BP4z9KsN6nGRTbVYI_c7VJSPQTBtkgcy27mlmlMoZIIgDll6e3vCYLocInmYWAmS6TlzAC8wEqKK6PBru3jl7A8');
const vectorPrkKey = await hmac(vectorAuth, vectorShared);
assert.equal(toBase64Url(vectorPrkKey), 'Snr3JMxaHVDXHWJn5wdC52WjpCtd2EIEGBykDcZW32k');
const vectorInfo = new Uint8Array([...new TextEncoder().encode('WebPush: info\0'), ...vectorUaPublic, ...vectorAsPublic]);
const vectorIkm = await expand(vectorPrkKey, vectorInfo, 32);
assert.equal(toBase64Url(vectorIkm), 'S4lYMb_L0FxCeq0WhDx813KgSYqU26kOyzWUdsXYyrg');
const vectorSalt = fromBase64Url('DGv6ra1nlYgDCS1FRnbzlw');
const vectorPrk = await hmac(vectorSalt, vectorIkm);
assert.equal(toBase64Url(await expand(vectorPrk, new TextEncoder().encode('Content-Encoding: aes128gcm\0'), 16)), 'oIhVW04MRdy2XN9CiKLxTg');
assert.equal(toBase64Url(await expand(vectorPrk, new TextEncoder().encode('Content-Encoding: nonce\0'), 12)), '4h_95klXJ5E_qnoN');
const keyInfo = new Uint8Array([...new TextEncoder().encode('WebPush: info\0'), ...clientPublic, ...encryptedRecord.slice(21, 86)]);
const ikm = await expand(authPrk, keyInfo, 32);
const prk = await hmac(encryptedRecord.slice(0, 16), ikm);
const cek = await expand(prk, new TextEncoder().encode('Content-Encoding: aes128gcm\0'), 16);
const nonce = await expand(prk, new TextEncoder().encode('Content-Encoding: nonce\0'), 12);
const aes = await crypto.subtle.importKey('raw', cek, { name: 'AES-GCM' }, false, ['decrypt']);
const decoded = new TextDecoder().decode(await crypto.subtle.decrypt({ name: 'AES-GCM', iv: nonce, tagLength: 128 }, aes, encryptedRecord.slice(86)));
assert.equal(decoded, '{"title":"Teste"}\x02', 'O receptor deve conseguir decifrar o payload da notificação.');

const dbCalls = [];
